def render(grid, scale, pal):
    rows = grid.strip('\n').split('\n')
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), rows
    im = Image.new('RGBA', (16 * scale, 16 * scale), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in pal:
                for dy in range(scale):
                    for dx in range(scale):
                        px[x * scale + dx, y * scale + dy] = pal[ch]
    return im


def main():
    items_dir = os.path.join(ROOT, 'items')
    for name, grid in ITEM_ICONS.items():
        render(grid, 2, AMBER).save(os.path.join(items_dir, name + '.png'), optimize=True)
    render(ITEM_ICONS['icon_placeholder'], 8, AMBER).save(
        os.path.join(items_dir, 'item_placeholder.png'), optimize=True)

    strip = Image.new('RGBA', (16 * len(UI_GLYPHS), 16), (0, 0, 0, 0))
    for i, grid in enumerate(UI_GLYPHS):
        strip.paste(render(grid, 1, WHITE), (i * 16, 0))
    strip.save(os.path.join(ROOT, 'ui_glyphs.png'), optimize=True)

    if '--sheet' in sys.argv:   # review contact sheet at 4x on the map's dark ground
        out = sys.argv[sys.argv.index('--sheet') + 1]
        n = len(UI_GLYPHS)
        sheet = Image.new('RGBA', (n * 72, 72), (20, 16, 8, 255))
        for i, grid in enumerate(UI_GLYPHS):
            g = render(grid, 4, WHITE)
            sheet.paste(g, (i * 72 + 4, 4), g)
        sheet.save(out)
    print(f'wrote {len(ITEM_ICONS)} item icons + ui_glyphs.png ({len(UI_GLYPHS)} glyphs)')


if __name__ == '__main__':
    main()
